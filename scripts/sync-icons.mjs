// Generates src/app/icons/phosphor-icons.ts from @phosphor-icons/core (regular weight, same as BrandSync's registry).
// Add an icon: append its Phosphor name below, then run `npm run icons:sync`.
import { readFileSync, writeFileSync } from 'node:fs';

const ICONS = [
  'house', 'cube', 'map-pin', 'credit-card', 'stack-simple', 'shopping-cart',
  'target', 'user', 'folder', 'chart-line', 'gear',
];

const entries = ICONS.map((name) => {
  const svg = readFileSync(`node_modules/@phosphor-icons/core/assets/regular/${name}.svg`, 'utf8');
  const viewBox = svg.match(/viewBox="([^"]+)"/)[1];
  const body = svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
  return `  '${name}': { viewBox: '${viewBox}', body: ${JSON.stringify(body)} },`;
});

writeFileSync(
  'src/app/icons/phosphor-icons.ts',
  `// GENERATED by scripts/sync-icons.mjs. Do not edit.\nexport const PHOSPHOR_ICONS = {\n${entries.join('\n')}\n};\n`,
);
console.log(`Wrote ${ICONS.length} icons`);
